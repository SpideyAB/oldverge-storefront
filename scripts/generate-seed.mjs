// Generates supabase/seed.sql (the DRAFT import of the sample catalogue) and supabase/seed-demo-publish.sql
// (an OPTIONAL, non-production script that publishes the samples for browsing in a preview).
//
//   node scripts/generate-seed.mjs
//
// The sample products are imported as DRAFT, sample-priced, with UNVERIFIED stock and UNVERIFIED photos
// (stand-ins from Unsplash). Nothing here makes anything purchasable and ordering stays closed.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = (file) => pathToFileURL(path.join(root, 'src', file)).href;
const { products } = await import(src('data/products.js'));
const { IMAGE_SIZES } = await import(src('data/imageSizes.js'));
const { copyFor } = await import(src('data/productCopy.js'));
const { POLICIES } = await import(src('data/policies.js'));

const q = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replaceAll("'", "''")}'`);
const FEATURED = ['quarter-zip-black', 'casio-mtp', 'quarter-zip-beige', 'seiko-5', 'quarter-zip-navy', 'timex-weekender', 'quarter-zip-olive', 'citizen-eco-drive', 'casio-a168', 'orient-bambino'];
const REQUESTED_BRANDS = [['rolex', 'Rolex'], ['patek-philippe', 'Patek Philippe'], ['cartier', 'Cartier'], ['franck-muller', 'Franck Muller'], ['best-win', 'Best Win']];
const SIZE_ORDER = ['S', 'M', 'L', 'XL', 'XXL'];
const slugify = (value) => String(value).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

// ---- provenance from docs/asset-sources.md (file -> photo page + credit)
const provenance = new Map();
for (const line of fs.readFileSync(path.join(root, 'docs/asset-sources.md'), 'utf8').split(/\r?\n/)) {
  const m = /^\|\s*`([^`]+\.jpg)`\s*\|[^|]*\|\s*`([^`]+)`\s*\|\s*([^|]+?)\s*\|/.exec(line);
  if (m) provenance.set(m[1], { page: `https://unsplash.com${m[2]}`, credit: m[3].replace(/\s*\(.*\)\s*$/, '') });
}
const sha = (file) => {
  const full = path.join(root, 'public', file.replace(/^\//, ''));
  return fs.existsSync(full) ? crypto.createHash('sha256').update(fs.readFileSync(full)).digest('hex') : null;
};
const sizeOf = (file) => (IMAGE_SIZES[file] ? { w: IMAGE_SIZES[file][0], h: IMAGE_SIZES[file][1] } : { w: null, h: null });

const out = [];
const push = (text = '') => out.push(text);
push('-- GENERATED by scripts/generate-seed.mjs. Do not edit by hand; edit the script or src/data and regenerate.');
push('-- DRAFT import of the sample catalogue. Sample prices, UNVERIFIED stock and photos, nothing purchasable.');
push('-- Safe to run more than once (every insert is conflict-guarded).');
push('');

push('insert into public.categories (slug, name, sort_order) values');
push("  ('watches', 'Watches', 10), ('quarter-zips', 'Quarter Zips', 20)");
push('on conflict (slug) do nothing;');
push('');

const brands = new Map(REQUESTED_BRANDS);
products.forEach((product) => brands.set(slugify(product.brand), product.brand));
push('-- Brands. The five requested watch brands exist with NO listings (their collections stay empty).');
push('insert into public.brands (slug, name) values');
push([...brands].map(([slug, name]) => `  (${q(slug)}, ${q(name)})`).join(',\n'));
push('on conflict (slug) do nothing;');
push('');

products.forEach((product, index) => {
  const categorySlug = product.category === 'Watches' ? 'watches' : 'quarter-zips';
  const description = copyFor(product).join('\n\n');
  push(`-- ${product.slug}`);
  push('insert into public.products (slug, legacy_id, name, description, category_id, brand_id, kind, style, group_key, sort_order)');
  push(`select ${q(product.slug)}, ${q(product.id)}, ${q(product.name)}, ${q(description)}, c.id, b.id, ${q(product.type)}, ${q(product.style)}, ${q(product.category === 'Quarter-Zips' ? 'quarter-zip' : null)}, ${(index + 1) * 10}`);
  push(`  from public.categories c left join public.brands b on b.slug = ${q(slugify(product.brand))} where c.slug = ${q(categorySlug)}`);
  push('on conflict (slug) do nothing;');
  const sizes = product.type === 'watch' ? [null] : [...product.sizes].sort((a, b) => SIZE_ORDER.indexOf(a) - SIZE_ORDER.indexOf(b));
  sizes.forEach((size, sizeIndex) => {
    const sku = `SMP-${slugify(product.slug).toUpperCase()}${size ? `-${size}` : '-OS'}`;
    push('insert into public.product_variants (product_id, sku, color_name, color_hex, size_label, price_pkr, sort_order)');
    push(`select p.id, ${q(sku)}, ${q(product.colors[0])}, ${q(product.artColor || null)}, ${q(size)}, ${product.price}, ${sizeIndex} from public.products p where p.slug = ${q(product.slug)}`);
    push('on conflict (sku) do nothing;');
  });
  // images: the cut-out is the cover (card image); the original photograph is the second gallery image
  const cutout = product.image;
  const original = cutout.replace(/-cutout\.webp$/, '.jpg');
  [[cutout, 'cutout', 0, true], [original, 'photo', 1, false]].forEach(([file, kind, order, cover]) => {
    const base = path.basename(file);
    const credit = provenance.get(path.basename(original));
    const dims = sizeOf(file);
    push('insert into public.product_images (product_id, bucket, path, kind, alt_text, width, height, sort_order, is_cover, source_name, source_url, licence, attribution, retrieved_on, approval_status, checksum_sha256)');
    push(`select p.id, 'product-private', ${q(`products/${product.slug}/v1/${base}`)}, ${q(kind)}, ${q(`${product.name}, ${kind === 'cutout' ? 'product view' : 'original photograph'}`)}, ${dims.w}, ${dims.h}, ${order}, ${cover}, 'Unsplash (stand-in photo)', ${q(credit?.page || null)}, 'Unsplash License', ${q(credit?.credit || null)}, '2026-10-17', 'unverified', ${q(sha(file))}`);
    push(`  from public.products p where p.slug = ${q(product.slug)} on conflict (bucket, path) do nothing;`);
  });
  push('');
});

// ---- editorial / site images (same stand-in photographs; keys are what the storefront asks for)
const SITE = {
  'quarter-zip-beige': ['quarter-zip-beige.jpg', 'Man in a beige quarter-zip'],
  'watch-seiko-sports': ['watch-seiko-sports.jpg', 'A sports watch on a white surface'],
  'oldverge-hero-model': ['oldverge-hero-model.jpg', 'Man wearing a grey-green quarter-zip, smiling'],
  'watch-timex-weekender': ['watch-timex-weekender.jpg', 'A field-style watch on a white surface'],
  'quarter-zip-neutral': ['quarter-zip-neutral.jpg', 'A grey sweater with a zipper'],
  'oldverge-watch-editorial': ['oldverge-watch-editorial.jpg', 'Close-up editorial photograph of a wristwatch'],
  'watch-hero-wrist': ['watch-hero-wrist.jpg', 'A watch on a wrist'],
  'watch-casio-mtp': ['watch-casio-mtp.jpg', 'A round analog watch'],
  'oldverge-hero-watch-detail': ['oldverge-hero-watch-detail.jpg', 'A wristwatch under a dark jacket sleeve'],
  'quarter-zip-soft-knit': ['quarter-zip-soft-knit.jpg', 'A dark knit sweater on a hanger'],
  'quarter-zip-soft-knit-cutout': ['quarter-zip-soft-knit-cutout.webp', 'A dark knit sweater on a hanger'],
};
push('-- Editorial and site images (home hero, category tiles, story). UNVERIFIED until approved.');
push('insert into public.site_images (key, bucket, path, alt_text, width, height, source_name, source_url, licence, approval_status) values');
push(Object.entries(SITE).map(([key, [file, alt]]) => {
  const credit = provenance.get(file.replace(/-cutout\.webp$/, '.jpg'));
  const dims = sizeOf(`/images/${file}`);
  return `  (${q(key)}, 'product-private', ${q(`site/${file}`)}, ${q(alt)}, ${dims.w}, ${dims.h}, 'Unsplash (stand-in photo)', ${q(credit?.page || null)}, 'Unsplash License', 'unverified')`;
}).join(',\n'));
push('on conflict (key) do nothing;');
push('');

push('-- Curated home carousel order, newsletter state.');
push("insert into public.store_settings (key, value, is_public) values");
push(`  ('home.featured', ${q(JSON.stringify(FEATURED))}::jsonb, true),`);
push("  ('newsletter.active', 'false'::jsonb, true)");
push('on conflict (key) do nothing;');
push('');

push('-- Policy text that already shipped on the site (it only states that no orders are accepted yet). Published as');
push('-- version 1 so the footer links keep working. updated_by stays null, so an owner must still publish each policy');
push('-- before ordering can be opened (see admin_ordering_readiness).');
POLICIES.forEach((policy) => {
  const sections = JSON.stringify(policy.sections.map((s) => ({ heading: s.heading, body: s.body })));
  push(`update public.policy_drafts set sections = ${q(sections)}::jsonb where slug = ${q(policy.slug)} and sections = '[]'::jsonb;`);
  push(`update public.policy_pages set published_sections = ${q(sections)}::jsonb, version = 1, published_at = now() where slug = ${q(policy.slug)} and published_at is null;`);
});
push('');

fs.writeFileSync(path.join(root, 'supabase/seed.sql'), `${out.join('\n')}\n`);

// ---- optional preview script
const demo = [];
demo.push('-- GENERATED by scripts/generate-seed.mjs. NON-PRODUCTION ONLY.');
demo.push('-- Publishes the sample products for BROWSING in a preview or local project. It does not verify stock, enable');
demo.push('-- payment, or open ordering: nothing becomes purchasable. Run it only after `node scripts/migrate-assets.mjs --publish-samples`');
demo.push('-- has copied the sample photographs into the public bucket.');
demo.push("update public.product_images set bucket = 'product-public', approval_status = 'approved', approved_at = now() where source_name = 'Unsplash (stand-in photo)';");
demo.push("update public.site_images set bucket = 'product-public', approval_status = 'approved' where source_name = 'Unsplash (stand-in photo)';");
demo.push("update public.products set status = 'published' where legacy_id is not null and status = 'draft';");
fs.writeFileSync(path.join(root, 'supabase/seed-demo-publish.sql'), `${demo.join('\n')}\n`);

console.log(`seed.sql: ${out.length} lines, ${products.length} products; seed-demo-publish.sql written`);
